
package q01;


public class Q01 {

    
    public static void main(String[] args) {
        double base = 2;
        double exponent = 10;
        double number = 81;

        double power = Math.pow(base, exponent);
        double squareRoot = Math.sqrt(number);

        System.out.println("2 ^ 10 = " + power);
        System.out.println("Square root of 81 = " + squareRoot);
    
    }
    
}
